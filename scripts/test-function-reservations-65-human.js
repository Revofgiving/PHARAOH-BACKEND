'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const rules = require('../rules-engine');
const root = path.resolve(__dirname, '..');
const functionSource = fs.readFileSync(path.join(root, 'function-manager.js'), 'utf8');
const flowSource = fs.readFileSync(path.join(root, 'donation-flow-manager.js'), 'utf8');
assert.match(functionSource, /RILASCIO FUNZIONI \(all'uscita L3\)/);
assert.match(functionSource, /async function rilasciaFunzioniL3/);
assert.match(flowSource, /functionManager\.rilasciaFunzioniL3\(/);
assert.equal(rules.IMPORTI.FUNZIONI_PRENOTATE_DAL_SECONDO, 5);
assert.equal(rules.IMPORTI.SACERDOTI_PRIMO_TURNO, 18);
assert.equal(rules.IMPORTI.SACERDOTI_DAL_SECONDO, 13);
assert.equal(rules.IMPORTI.SACERDOTI_PRIMO_TURNO - rules.IMPORTI.FUNZIONI_PRENOTATE_DAL_SECONDO, 13);
